interface MsgLike {
  role: string;
  content?: string;
  tool_calls?: { id: string; function: { name: string; arguments: string } }[];
}

function lastUser(msgs: MsgLike[]): string {
  for (let i = msgs.length - 1; i >= 0; i--) if (msgs[i].role === "user") return String(msgs[i].content ?? "");
  return "";
}
function toolResultCount(msgs: MsgLike[]): number {
  /* 只数「最后一条用户消息之后」的 tool 结果:同一主会话里可能先跑过
     冷读修复等流程,全局计数会让长剧本(采用门)跳过开头几步。 */
  let lastUserIdx = -1;
  for (let i = msgs.length - 1; i >= 0; i--) if (msgs[i].role === "user") { lastUserIdx = i; break; }
  let count = 0;
  for (let i = lastUserIdx + 1; i < msgs.length; i++) if (msgs[i].role === "tool") count++;
  return count;
}

