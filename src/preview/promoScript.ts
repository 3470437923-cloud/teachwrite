/**
 * 宣传片剧本引擎(仅 ?promo=1 时启用;默认预览路径不受影响)。
 *
 * 读真实请求体(messages 最后一条用户消息 + 已有 tool 结果数),
 * 按剧本回放 OpenAI 形态的 SSE 行:思考流、正文流、工具调用增量、
 * question 弹窗、采用门回写。宣传片里出现的每一帧界面都走真实渲染路径。
 */

const CRLF = "\r\n";
const j = (o: unknown) => JSON.stringify(o);

const cLine = (t: string) => `data: ${j({ choices: [{ delta: { content: t } }] })}`;
const rLine = (t: string) => `data: ${j({ choices: [{ delta: { reasoning_content: t } }] })}`;
const fLine = (reason: string | null) => `data: ${j({ choices: [{ delta: {}, finish_reason: reason }] })}`;
const usageLine = (pt: number, ct: number) =>
  `data: ${j({ choices: [], usage: { prompt_tokens: pt, completion_tokens: ct, prompt_cache_hit_tokens: Math.floor(pt * 0.87), prompt_cache_miss_tokens: Math.ceil(pt * 0.13) } })}`;

/** 工具调用:首片带 id+name,arguments 分片(与真实上游增量协议一致)→ tool_calls 收尾 */
function toolSteps(id: string, name: string, args: string): { kind: string; data: string }[] {
  const steps: { kind: string; data: string }[] = [
    { kind: "line", data: `data: ${j({ choices: [{ delta: { tool_calls: [{ index: 0, id, type: "function", function: { name, arguments: "" } }] } }] })}` },
  ];
  for (let i = 0; i < args.length; i += 24) {
    steps.push({ kind: "line", data: `data: ${j({ choices: [{ delta: { tool_calls: [{ index: 0, function: { arguments: args.slice(i, i + 24) } }] } }] })}` });
  }
  steps.push({ kind: "line", data: fLine("tool_calls") });
  steps.push({ kind: "line", data: usageLine(5200 + (args.length % 900), 120 + Math.floor(args.length / 3)) });
  steps.push({ kind: "line", data: "data: [DONE]" });
  steps.push({ kind: "done", data: "" });
  return steps;
}

/** 正文流:thinking(可空)→ content 片 → stop → usage → DONE */
function textSteps(thinking: string | null, parts: string[], pt = 6400, ct = 900): { kind: string; data: string }[] {
  const steps: { kind: string; data: string }[] = [];
  if (thinking) steps.push({ kind: "line", data: rLine(thinking) });
  for (const p of parts) steps.push({ kind: "line", data: cLine(p) });
  steps.push({ kind: "line", data: fLine("stop") });
  steps.push({ kind: "line", data: usageLine(pt, ct) });
  steps.push({ kind: "line", data: "data: [DONE]" });
  steps.push({ kind: "done", data: "" });
  return steps;
}

